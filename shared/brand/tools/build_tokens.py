"""Generate shared/brand/brand.css from tokens.json and verify palette contrast.

Usage: uv run python shared/brand/tools/build_tokens.py

tokens.json is the only place brand values are written by hand. shared/colors.py and
shared/typography.py read it at import time, so only the CSS needs generating.
"""

import json
from pathlib import Path

BRAND_DIR = Path(__file__).resolve().parents[1]
MINIMUM_LARGE_TEXT_CONTRAST = 3.0


def hex_to_rgb(color: str) -> tuple[int, int, int]:
    value = color.lstrip("#")
    return int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16)


def relative_luminance(color: str) -> float:
    def linear(channel: int) -> float:
        scaled = channel / 255
        return (
            scaled / 12.92 if scaled <= 0.03928 else ((scaled + 0.055) / 1.055) ** 2.4
        )

    red, green, blue = hex_to_rgb(color)
    return 0.2126 * linear(red) + 0.7152 * linear(green) + 0.0722 * linear(blue)


def contrast_ratio(first: str, second: str) -> float:
    lighter, darker = sorted(
        (relative_luminance(first), relative_luminance(second)), reverse=True
    )
    return (lighter + 0.05) / (darker + 0.05)


def rgb_channels(color: str) -> str:
    return " ".join(str(channel) for channel in hex_to_rgb(color))


def build_css(tokens: dict) -> str:
    colors = tokens["color"]
    opacity = tokens["opacity"]
    fonts = tokens["font"]
    reel = tokens["reel"]
    faces = "\n".join(
        f'@font-face {{\n  font-family: "{font["family"]}";\n'
        f'  src: url("{font["file"]}") format("truetype");\n'
        f"  font-weight: {font['css_weight']};\n  font-style: normal;\n  font-display: block;\n}}"
        for font in fonts.values()
    )
    return f"""/* GENERATED by tools/build_tokens.py from tokens.json. Do not edit by hand. */
{faces}

:root {{
  --brand-background: {colors["background"]};
  --brand-ink: {colors["ink"]};
  --brand-accent: {colors["accent"]};
  /* Tints are the three colors at reduced opacity, never new colors. */
  --brand-ink-soft: rgb({rgb_channels(colors["ink"])} / {opacity["ink_soft"]});
  --brand-ink-faint: rgb({rgb_channels(colors["ink"])} / {opacity["ink_faint"]});
  --brand-shadow: rgb({rgb_channels(colors["ink"])} / {opacity["shadow"]});
  --brand-font-display: "{fonts["display"]["family"]}", serif;
  --brand-font-caption: "{fonts["caption"]["family"]}", serif;
  --brand-font-code: "{fonts["code"]["family"]}", monospace;
  --reel-width: {reel["width"]}px;
  --reel-height: {reel["height"]}px;
  --safe-top: {reel["safe_top"]}px;
  --safe-bottom: {reel["safe_bottom"]}px;
  --safe-side: {reel["safe_side"]}px;
}}

* {{ margin: 0; padding: 0; box-sizing: border-box; }}
html, body {{
  width: var(--reel-width);
  height: var(--reel-height);
  overflow: hidden;
  background: var(--brand-background);
}}

/* Surfaces. Paper urls live here, not in custom properties, so they resolve against
   this file wherever the kit is copied. */
.bp-paper {{
  position: absolute;
  inset: 0;
  background: var(--brand-background) url("{tokens["paper"][0]}") center / cover no-repeat;
}}
.bp-paper.is-folded {{ background-image: url("{tokens["paper"][1]}"); }}
.bp-paper.is-quiet {{ background-image: url("{tokens["paper"][2]}"); }}
.bp-ink-surface {{ position: absolute; inset: 0; background: var(--brand-ink); color: var(--brand-background); }}

/* Torn orange reveal. The sheets share one tear; these offsets seal them at mid-frame.
   Each sheet is 1200 px tall, with the seam at 1000 px (top) and 200 px (bottom). */
.bp-torn-top, .bp-torn-bottom {{
  position: absolute;
  left: 0;
  width: 1080px;
  height: 1200px;
  background: center / 100% 100% no-repeat;
}}
.bp-torn-top {{ top: -40px; background-image: url("torn/torn_top.webp"); }}
.bp-torn-bottom {{ top: 760px; background-image: url("torn/torn_bottom.webp"); }}

/* Everything readable goes inside this box: it is the Instagram-safe area. */
.bp-safe {{
  position: absolute;
  top: var(--safe-top);
  left: var(--safe-side);
  right: var(--safe-side);
  bottom: var(--safe-bottom);
}}

/* Type. Display is for 64 px and up; Caption for 34 to 60 px; Code for code only. */
.bp-headline {{
  font-family: var(--brand-font-display);
  font-weight: {fonts["display"]["css_weight"]};
  font-size: 112px;
  line-height: 1.02;
  letter-spacing: -0.012em;
  color: var(--brand-ink);
  font-kerning: normal;
}}
.bp-caption {{
  font-family: var(--brand-font-caption);
  font-weight: {fonts["caption"]["css_weight"]};
  font-size: 48px;
  line-height: 1.2;
  color: var(--brand-ink);
  font-kerning: normal;
}}
.bp-code {{
  font-family: var(--brand-font-code);
  font-weight: {fonts["code"]["css_weight"]};
  font-size: 40px;
  line-height: 1.35;
  color: var(--brand-ink);
  /* Coding ligatures would redraw != and -> as glyphs viewers may misread. */
  font-variant-ligatures: none;
}}
.bp-accent {{ color: var(--brand-accent); }}
.bp-soft {{ color: var(--brand-ink-soft); }}
"""


def main() -> None:
    tokens = json.loads((BRAND_DIR / "tokens.json").read_text(encoding="utf-8"))
    colors = tokens["color"]
    pairs = {
        "ink / background": (colors["ink"], colors["background"]),
        "accent / background": (colors["accent"], colors["background"]),
        "accent / ink": (colors["accent"], colors["ink"]),
        "background / accent": (colors["background"], colors["accent"]),
        "ink / accent": (colors["ink"], colors["accent"]),
    }
    for label, (first, second) in pairs.items():
        ratio = contrast_ratio(first, second)
        print(f"{label:22s} {ratio:5.2f}:1")
        if ratio < MINIMUM_LARGE_TEXT_CONTRAST:
            raise SystemExit(f"{label} is below {MINIMUM_LARGE_TEXT_CONTRAST}:1")
    (BRAND_DIR / "brand.css").write_text(
        build_css(tokens), encoding="utf-8", newline="\n"
    )
    print("wrote brand.css")


if __name__ == "__main__":
    main()
